CREATE TABLE dim_usuario (
 u_id_usuario NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 u_nombre VARCHAR2(100) NOT NULL,
 u_correo VARCHAR2(150) NOT NULL UNIQUE,
 u_ciudad VARCHAR2(80),
 u_fecha_registro DATE DEFAULT SYSDATE NOT NULL,
 u_estado VARCHAR2(10) DEFAULT 'Activo' NOT NULL,
 CONSTRAINT ck_usuario_estado CHECK (u_estado IN ('Activo','Inactivo'))
);
CREATE TABLE dim_categoria (
 c_id_categoria NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 c_nombre VARCHAR2(100) NOT NULL UNIQUE,
 c_tipo VARCHAR2(10) NOT NULL,
 c_descripcion VARCHAR2(250),
 CONSTRAINT ck_categoria_tipo CHECK (c_tipo IN ('Ingreso','Gasto'))
);
CREATE TABLE dim_tiempo (
 t_id_tiempo NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 t_fecha DATE NOT NULL UNIQUE,
 t_dia NUMBER(2) NOT NULL CHECK (t_dia BETWEEN 1 AND 31),
 t_mes NUMBER(2) NOT NULL CHECK (t_mes BETWEEN 1 AND 12),
 "T_AÑO" NUMBER(4) NOT NULL,
 t_trimestre NUMBER(1) NOT NULL CHECK (t_trimestre BETWEEN 1 AND 4),
 t_dia_semana VARCHAR2(12) NOT NULL,
 CONSTRAINT ck_dia_semana CHECK (t_dia_semana IN ('Lunes','Martes','Miércoles','Jueves','Viernes','Sábado','Domingo'))
);
CREATE TABLE fact_transaccion (
 tr_id_transaccion NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
 tr_id_usuario NUMBER NOT NULL REFERENCES dim_usuario(u_id_usuario),
 tr_id_categoria NUMBER NOT NULL REFERENCES dim_categoria(c_id_categoria),
 tr_id_tiempo NUMBER NOT NULL REFERENCES dim_tiempo(t_id_tiempo),
 tr_monto NUMBER(14,2) NOT NULL CHECK (tr_monto > 0),
 tr_metodo_pago VARCHAR2(30) NOT NULL CHECK (tr_metodo_pago IN ('Efectivo','Tarjeta débito','Tarjeta crédito','Transferencia')),
 tr_descripcion VARCHAR2(250)
);
CREATE INDEX ix_tr_usuario_tiempo ON fact_transaccion(tr_id_usuario,tr_id_tiempo);
CREATE INDEX ix_tr_categoria ON fact_transaccion(tr_id_categoria);
COMMIT;
